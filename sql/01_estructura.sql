-- 1. CREACIÓN DEL ESQUEMA ADUANA
-- Aislamiento de objetos del laboratorio sin interferir con esquemas de Supabase (auth, storage, etc.)
CREATE SCHEMA IF NOT EXISTS aduana;

SET search_path TO aduana, public;

-- ----------------------------------------------------------------------------
-- TABLA 1: aduana.pais
-- Catálogo de países normalizado (origen de mercancía, procedencia de contenedor, importador)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS aduana.pais (
    id_pais INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_iso_alfa2 VARCHAR(2) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_pais_codigo UNIQUE (codigo_iso_alfa2),
    CONSTRAINT uq_pais_nombre UNIQUE (nombre),
    CONSTRAINT check_pais_codigo_formato CHECK (length(codigo_iso_alfa2) = 2 AND codigo_iso_alfa2 = upper(codigo_iso_alfa2))
);

-- ----------------------------------------------------------------------------
-- TABLA 2: aduana.importador
-- Empresas jurídicas o personas físicas registradas ante la aduana
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS aduana.importador (
    id_importador INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pais INTEGER NOT NULL,
    identificacion_tributaria VARCHAR(20) NOT NULL,
    razon_social VARCHAR(150) NOT NULL,
    correo_contacto VARCHAR(100) NOT NULL,
    telefono_contacto VARCHAR(25) NOT NULL,
    direccion_fiscal TEXT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_importador_identificacion UNIQUE (identificacion_tributaria),
    CONSTRAINT check_importador_razon_social CHECK (trim(razon_social) <> ''),
    CONSTRAINT check_importador_correo CHECK (position('@' IN correo_contacto) > 1),
    CONSTRAINT fk_importador_pais FOREIGN KEY (id_pais)
        REFERENCES aduana.pais (id_pais) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- ----------------------------------------------------------------------------
-- TABLA 3: aduana.agente_aduanal
-- Auxiliar autorizado de la función pública aduanera (Ley General de Aduanas N.º 7557)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS aduana.agente_aduanal (
    id_agente_aduanal INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_licencia VARCHAR(20) NOT NULL,
    nombre_completo VARCHAR(150) NOT NULL,
    correo VARCHAR(100) NOT NULL,
    telefono VARCHAR(25) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_agente_licencia UNIQUE (numero_licencia),
    CONSTRAINT check_agente_nombre CHECK (trim(nombre_completo) <> ''),
    CONSTRAINT check_agente_correo CHECK (position('@' IN correo) > 1)
);

-- ----------------------------------------------------------------------------
-- TABLA 4: aduana.categoria_arancelaria
-- Nomenclatura del Sistema Armonizado (SA de la OMA)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS aduana.categoria_arancelaria (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_capitulo VARCHAR(2) NOT NULL,
    codigo_partida VARCHAR(4) NOT NULL,
    codigo_subpartida VARCHAR(6) NOT NULL,
    descripcion TEXT NOT NULL,
    arancel_base_porcentaje NUMERIC(5,2) NOT NULL,
    CONSTRAINT uq_categoria_subpartida UNIQUE (codigo_subpartida),
    CONSTRAINT check_categoria_capitulo CHECK (length(codigo_capitulo) = 2),
    CONSTRAINT check_categoria_partida CHECK (length(codigo_partida) = 4),
    CONSTRAINT check_categoria_subpartida CHECK (length(codigo_subpartida) = 6),
    CONSTRAINT check_categoria_arancel CHECK (arancel_base_porcentaje >= 0.00 AND arancel_base_porcentaje <= 100.00)
);

-- ----------------------------------------------------------------------------
-- TABLA 5: aduana.producto
-- Catálogo de mercancías comercializables. El origen define «mercancías de China».
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS aduana.producto (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria INTEGER NOT NULL,
    id_pais_origen INTEGER NOT NULL,
    codigo_sku VARCHAR(30) NOT NULL,
    nombre_comercial VARCHAR(150) NOT NULL,
    descripcion TEXT,
    unidad_medida VARCHAR(20) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_producto_sku UNIQUE (codigo_sku),
    CONSTRAINT check_producto_nombre CHECK (trim(nombre_comercial) <> ''),
    CONSTRAINT check_producto_unidad CHECK (unidad_medida IN ('unidades', 'kilogramos', 'litros', 'cajas')),
    CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria)
        REFERENCES aduana.categoria_arancelaria (id_categoria) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_producto_pais_origen FOREIGN KEY (id_pais_origen)
        REFERENCES aduana.pais (id_pais) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- ----------------------------------------------------------------------------
-- TABLA 6: aduana.contenedor
-- Unidades intermodales de transporte (ISO 6346) y país de procedencia física
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS aduana.contenedor (
    id_contenedor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pais_procedencia INTEGER NOT NULL,
    numero_sigla VARCHAR(11) NOT NULL,
    tipo_dimension VARCHAR(20) NOT NULL,
    tara_kg NUMERIC(10,2) NOT NULL,
    capacidad_max_kg NUMERIC(10,2) NOT NULL,
    estado_operativo VARCHAR(25) NOT NULL,
    CONSTRAINT uq_contenedor_sigla UNIQUE (numero_sigla),
    CONSTRAINT check_contenedor_sigla_len CHECK (length(numero_sigla) = 11),
    CONSTRAINT check_contenedor_tipo CHECK (tipo_dimension IN ('20GP', '40GP', '40HC', '45HC', '20RF', '40RF')),
    CONSTRAINT check_contenedor_pesos CHECK (tara_kg > 0 AND capacidad_max_kg > tara_kg),
    CONSTRAINT check_contenedor_estado CHECK (estado_operativo IN ('En Transito', 'En Puerto', 'En Inspeccion', 'En Bodega', 'Despachado')),
    CONSTRAINT fk_contenedor_pais_procedencia FOREIGN KEY (id_pais_procedencia)
        REFERENCES aduana.pais (id_pais) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- ----------------------------------------------------------------------------
-- TABLA 7: aduana.ficha_contenedor
-- Entidad 13: Relación 1:1 estricta con contenedor. PK es a la vez FK.
-- Participación: 0..1 desde contenedor; 1..1 desde ficha_contenedor.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS aduana.ficha_contenedor (
    id_contenedor INTEGER PRIMARY KEY,
    numero_marchamo_aduana VARCHAR(30) NOT NULL,
    temperatura_controlada_c NUMERIC(5,2),
    humedad_relativa_porc NUMERIC(5,2),
    observacion_inspeccion_fisica TEXT,
    fecha_emision_ficha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ficha_marchamo UNIQUE (numero_marchamo_aduana),
    CONSTRAINT check_ficha_humedad CHECK (humedad_relativa_porc IS NULL OR (humedad_relativa_porc >= 0.00 AND humedad_relativa_porc <= 100.00)),
    CONSTRAINT fk_ficha_contenedor FOREIGN KEY (id_contenedor)
        REFERENCES aduana.contenedor (id_contenedor) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- ----------------------------------------------------------------------------
-- TABLA 8: aduana.declaracion_aduanera
-- Cabecera del Documento Único Aduanero (DUA). Valor declarado es dinámico.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS aduana.declaracion_aduanera (
    id_declaracion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_importador INTEGER NOT NULL,
    id_agente_aduanal INTEGER NOT NULL,
    id_contenedor INTEGER NOT NULL,
    numero_dua VARCHAR(20) NOT NULL,
    regimen VARCHAR(25) NOT NULL,
    estado VARCHAR(25) NOT NULL,
    fecha_declaracion DATE NOT NULL,
    fecha_ingreso_recinto TIMESTAMPTZ NOT NULL,
    moneda VARCHAR(3) NOT NULL DEFAULT 'USD',
    CONSTRAINT uq_declaracion_dua UNIQUE (numero_dua),
    CONSTRAINT check_declaracion_dua_formato CHECK (numero_dua ~ '^DUA-2026-[0-9]{4}$'),
    CONSTRAINT check_declaracion_regimen CHECK (regimen IN ('Importacion', 'Exportacion', 'Transito', 'Deposito')),
    CONSTRAINT check_declaracion_estado CHECK (estado IN ('Retenida', 'Liberada', 'En Inspeccion')),
    CONSTRAINT check_declaracion_moneda CHECK (moneda = 'USD'),
    CONSTRAINT fk_declaracion_importador FOREIGN KEY (id_importador)
        REFERENCES aduana.importador (id_importador) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_declaracion_agente FOREIGN KEY (id_agente_aduanal)
        REFERENCES aduana.agente_aduanal (id_agente_aduanal) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_declaracion_contenedor FOREIGN KEY (id_contenedor)
        REFERENCES aduana.contenedor (id_contenedor) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- ----------------------------------------------------------------------------
-- TABLA 9: aduana.detalle_declaracion
-- Líneas de mercancía declarada (N:M). Clave primaria compuesta.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS aduana.detalle_declaracion (
    id_declaracion INTEGER NOT NULL,
    numero_linea INTEGER NOT NULL,
    id_producto INTEGER NOT NULL,
    cantidad NUMERIC(12,2) NOT NULL,
    unidad_medida VARCHAR(20) NOT NULL,
    valor_unitario NUMERIC(14,2) NOT NULL,
    tasa_arancelaria_porc NUMERIC(5,2) NOT NULL,
    descripcion_arancelaria TEXT NOT NULL,
    CONSTRAINT pk_detalle_declaracion PRIMARY KEY (id_declaracion, numero_linea),
    CONSTRAINT check_detalle_linea_pos CHECK (numero_linea > 0),
    CONSTRAINT check_detalle_cantidad_pos CHECK (cantidad > 0.00),
    CONSTRAINT check_detalle_unidad CHECK (unidad_medida IN ('unidades', 'kilogramos', 'litros', 'cajas')),
    CONSTRAINT check_detalle_valor_pos CHECK (valor_unitario >= 0.00),
    CONSTRAINT check_detalle_tasa CHECK (tasa_arancelaria_porc >= 0.00 AND tasa_arancelaria_porc <= 100.00),
    CONSTRAINT fk_detalle_declaracion FOREIGN KEY (id_declaracion)
        REFERENCES aduana.declaracion_aduanera (id_declaracion) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto)
        REFERENCES aduana.producto (id_producto) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- ----------------------------------------------------------------------------
-- TABLA 10: aduana.bodega
-- Instalaciones de almacenamiento y recintos bajo potestad fiscal
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS aduana.bodega (
    id_bodega INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_bodega VARCHAR(15) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    tipo_bodega VARCHAR(30) NOT NULL,
    ubicacion_recinto VARCHAR(150) NOT NULL,
    capacidad_volumen_m3 NUMERIC(10,2) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_bodega_codigo UNIQUE (codigo_bodega),
    CONSTRAINT check_bodega_tipo CHECK (tipo_bodega IN ('Fiscal', 'Refrigerada', 'General', 'Mercancias Peligrosas')),
    CONSTRAINT check_bodega_capacidad CHECK (capacidad_volumen_m3 > 0.00)
);

-- ----------------------------------------------------------------------------
-- TABLA 11: aduana.inventario_bodega
-- Existencias en bodega con trazabilidad granular a la línea del DUA
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS aduana.inventario_bodega (
    id_inventario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bodega INTEGER NOT NULL,
    id_declaracion INTEGER NOT NULL,
    numero_linea INTEGER NOT NULL,
    id_producto INTEGER NOT NULL,
    ubicacion_estante VARCHAR(30) NOT NULL,
    cantidad_almacenada NUMERIC(12,2) NOT NULL,
    unidad_medida VARCHAR(20) NOT NULL,
    fecha_ingreso TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_salida TIMESTAMPTZ,
    CONSTRAINT uq_bodega_detalle_declaracion UNIQUE (id_bodega, id_declaracion, numero_linea),
    CONSTRAINT check_inventario_cantidad CHECK (cantidad_almacenada >= 0.00),
    CONSTRAINT check_inventario_unidad CHECK (unidad_medida IN ('unidades', 'kilogramos', 'litros', 'cajas')),
    CONSTRAINT check_inventario_fechas CHECK (fecha_salida IS NULL OR fecha_salida >= fecha_ingreso),
    CONSTRAINT fk_inventario_bodega FOREIGN KEY (id_bodega)
        REFERENCES aduana.bodega (id_bodega) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_inventario_detalle FOREIGN KEY (id_declaracion, numero_linea)
        REFERENCES aduana.detalle_declaracion (id_declaracion, numero_linea) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_inventario_producto FOREIGN KEY (id_producto)
        REFERENCES aduana.producto (id_producto) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- ----------------------------------------------------------------------------
-- TABLA 12: aduana.funcionario
-- Personal aduanero y jerarquía supervisora recursiva
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS aduana.funcionario (
    id_funcionario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_supervisor INTEGER,
    numero_empleado VARCHAR(20) NOT NULL,
    nombre_completo VARCHAR(150) NOT NULL,
    puesto_cargo VARCHAR(100) NOT NULL,
    area_adscripcion VARCHAR(100) NOT NULL,
    correo_institucional VARCHAR(100) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_funcionario_empleado UNIQUE (numero_empleado),
    CONSTRAINT uq_funcionario_correo UNIQUE (correo_institucional),
    CONSTRAINT check_funcionario_correo CHECK (position('@' IN correo_institucional) > 1),
    CONSTRAINT check_no_autosupervision CHECK (id_supervisor IS NULL OR id_supervisor <> id_funcionario),
    CONSTRAINT fk_funcionario_supervisor FOREIGN KEY (id_supervisor)
        REFERENCES aduana.funcionario (id_funcionario) ON DELETE SET NULL ON UPDATE CASCADE
);

-- ----------------------------------------------------------------------------
-- TABLA 13: aduana.inspeccion
-- Actas de reconocimiento físico y aforo documental suscritos por funcionario
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS aduana.inspeccion (
    id_inspeccion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_declaracion INTEGER NOT NULL,
    id_funcionario INTEGER NOT NULL,
    numero_acta VARCHAR(30) NOT NULL,
    tipo_inspeccion VARCHAR(25) NOT NULL,
    fecha_inspeccion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resultado VARCHAR(25) NOT NULL,
    observaciones TEXT NOT NULL,
    dictamen_firmado BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_inspeccion_acta UNIQUE (numero_acta),
    CONSTRAINT check_inspeccion_tipo CHECK (tipo_inspeccion IN ('Fisica', 'Documental', 'Escaner No Intrusivo')),
    CONSTRAINT check_inspeccion_resultado CHECK (resultado IN ('Conforme', 'Discrepancia Arancelaria', 'Retencion Preventiva', 'Comiso')),
    CONSTRAINT check_inspeccion_observaciones CHECK (trim(observaciones) <> ''),
    CONSTRAINT fk_inspeccion_declaracion FOREIGN KEY (id_declaracion)
        REFERENCES aduana.declaracion_aduanera (id_declaracion) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_inspeccion_funcionario FOREIGN KEY (id_funcionario)
        REFERENCES aduana.funcionario (id_funcionario) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- ============================================================================
-- ÍNDICES ESTRATÉGICOS PARA OPTIMIZACIÓN DE FK Y CONSULTAS DE NEGOCIO
-- ============================================================================

-- Índices en claves foráneas
CREATE INDEX IF NOT EXISTS idx_importador_id_pais ON aduana.importador (id_pais);
CREATE INDEX IF NOT EXISTS idx_producto_id_categoria ON aduana.producto (id_categoria);
CREATE INDEX IF NOT EXISTS idx_producto_id_pais_origen ON aduana.producto (id_pais_origen);
CREATE INDEX IF NOT EXISTS idx_contenedor_id_pais_procedencia ON aduana.contenedor (id_pais_procedencia);
CREATE INDEX IF NOT EXISTS idx_declaracion_id_importador ON aduana.declaracion_aduanera (id_importador);
CREATE INDEX IF NOT EXISTS idx_declaracion_id_agente ON aduana.declaracion_aduanera (id_agente_aduanal);
CREATE INDEX IF NOT EXISTS idx_declaracion_id_contenedor ON aduana.declaracion_aduanera (id_contenedor);
CREATE INDEX IF NOT EXISTS idx_detalle_id_producto ON aduana.detalle_declaracion (id_producto);
CREATE INDEX IF NOT EXISTS idx_inventario_id_bodega ON aduana.inventario_bodega (id_bodega);
CREATE INDEX IF NOT EXISTS idx_inventario_id_producto ON aduana.inventario_bodega (id_producto);
CREATE INDEX IF NOT EXISTS idx_funcionario_id_supervisor ON aduana.funcionario (id_supervisor);
CREATE INDEX IF NOT EXISTS idx_inspeccion_id_declaracion ON aduana.inspeccion (id_declaracion);
CREATE INDEX IF NOT EXISTS idx_inspeccion_id_funcionario ON aduana.inspeccion (id_funcionario);

-- Índices para acelerar las consultas de negocio del laboratorio
-- Consulta 1: Declaraciones de importación en rango de fechas
CREATE INDEX IF NOT EXISTS idx_declaracion_regimen_fecha 
    ON aduana.declaracion_aduanera (regimen, fecha_declaracion);

-- Consulta 2: Declaraciones retenidas y producto originario
CREATE INDEX IF NOT EXISTS idx_declaracion_estado 
    ON aduana.declaracion_aduanera (estado);

-- Consulta 6 y 8: Inventario activo y cálculo de permanencia
CREATE INDEX IF NOT EXISTS idx_inventario_cantidad_salida 
    ON aduana.inventario_bodega (cantidad_almacenada, fecha_salida);
